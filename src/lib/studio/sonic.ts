export const MIN_STRUCTURED_SECONDS = 12;

/** The exact tempo renderMusic() uses for a mood+seed (beats start at t=0), so editors can cut on the beat without detection. */
export function musicBpm(mood: Exclude<Mood, 'none'>, seed = 1, overrides?: Partial<Recipe>): number {
  return ({ ...RECIPES[mood], ...(overrides ?? {}) }).bpm * (1 + ((seed % 5) - 2) * 0.015);
}

export async function renderMusic(o: MusicOptions): Promise<Stereo> {
  const rc: Recipe = { ...RECIPES[o.mood], ...(o.overrides ?? {}) };
  if (o.structure ?? o.seconds >= MIN_STRUCTURED_SECONDS) return renderStructured(o, rc);
  const seed = o.seed ?? 1, R = rng(seed * 7919 + 13);
  const I = o.intensity === 'low' ? 0.65 : o.intensity === 'high' ? 1.25 : 1;
  const bpm = rc.bpm * (1 + ((seed % 5) - 2) * 0.015); // small tempo variation per seed => audibly different variations
  const beat = 60 / bpm, bar = beat * 4, step = beat / 4;
  const total = Math.max(2, o.seconds + 0.5), bars = Math.ceil(total / bar);
  const arranged = !!(rc.layerIn || rc.arc || rc.outroSec);       // legacy recipes render exactly as before; the arrangement shaping is opt-in
  const scale = SCALES[rc.scale];
  const rootShift = [0, 0, 2, -2, 5, -5][seed % 6]; // key variation per seed
  const root = rc.root + rootShift;

  const padL = mono(total), padR = mono(total), bass = mono(total), arp = mono(total), pno = mono(total), perc = mono(total), tex = mono(total);

  for (let b = 0; b < bars; b++) {
    const t0 = b * bar, deg = rc.prog[b % rc.prog.length];
    const chord = [0, 2, 4].map((k) => degNote(scale, root + 12, deg + k));
    for (const [k, m] of chord.entries()) {
      addNote(padL, t0, bar * 0.95, midiToHz(m), rc.pad.wave, bar * 0.35, 0.3, 0.8, bar * 0.4, rc.pad.level * 0.4, rc.pad.detune, 0.15 * (k + 1));
      addNote(padR, t0, bar * 0.95, midiToHz(m), rc.pad.wave, bar * 0.35, 0.3, 0.8, bar * 0.4, rc.pad.level * 0.4, -rc.pad.detune, 0.2 * (k + 1));
    }
    const bn = degNote(scale, root - 12, deg);
    if (rc.bass === 'sub') addNote(bass, t0, bar * 0.9, midiToHz(bn), 'sine', 0.05, 0.2, 0.85, 0.3, rc.bassLevel * 0.7);
    else if (rc.bass === 'pulse') for (let s = 0; s < 8; s++) {
      const accent = rc.perc === 'afro' ? [0, 3, 5, 6].includes(s) : s % 2 === 0;
      if (accent) addNote(bass, t0 + s * step * 2, step * 1.6, midiToHz(bn + (s === 6 && rc.perc !== 'four' ? 7 : 0)), 'saw', 0.004, 0.08, 0.5, 0.06, rc.bassLevel * 0.35);
    }
    if (rc.arp) {
      const per = rc.arp.div === 4 ? 16 : 8, dur = bar / per, tones = [chord[0] + 12, chord[1] + 12, chord[2] + 12, chord[1] + 24];
      for (let s = 0; s < per; s++) if (R() < 0.55 + 0.35 * Math.min(1, I)) addNote(arp, t0 + s * dur, dur * 0.8, midiToHz(tones[(s * (R() < 0.2 ? 3 : 1)) % tones.length]), rc.arp.wave, 0.003, 0.09, 0.15, 0.09, rc.arp.level * 0.3);
    }
    if (rc.piano) {
      const hits = rc.perc === 'none' || rc.perc === 'minimal' ? [0, 8] : [0, 6, 10];
      for (const s of hits) for (const [k, m] of chord.entries()) if (k === 0 || s === 0 || R() < 0.5)
        for (const [h, hl] of [[1, 1], [2, 0.4], [3, 0.18], [4, 0.08]] as const) addNote(pno, t0 + s * step + k * 0.012, 0.01, midiToHz(m + (k === 0 ? 0 : 12)) * h, 'sine', 0.002, 0.9 / h, 0, 1.1 / h + 0.4, rc.pianoLevel * 0.16 * hl);
    }
    // percussion
    const p = rc.perc, L = rc.percLevel * I * 0.5;
    if (p !== 'none') for (let s = 0; s < 16; s++) {
      const at = t0 + s * step;
      if (p === 'four') { if (s % 4 === 0) drum(perc, at, 'kick', L * 1.1); if (s % 8 === 4) drum(perc, at, 'snare', L * 0.8, 1, R); if (s % 4 === 2) drum(perc, at, 'hat', L * 0.45, 1, R); }
      else if (p === 'soft') { if (s === 0 || s === 8) drum(perc, at, 'kick', L * 0.8); if (s === 4 || s === 12) drum(perc, at, 'hat', L * 0.5, 1, R); }
      else if (p === 'cinematic') { if (s === 0) drum(perc, at, 'tom', L * 1.2, 0.8); if (s === 10 && b % 2 === 1) drum(perc, at, 'tom', L * 0.8, 1.1); }
      else if (p === 'afro') {
        if ([0, 6, 10].includes(s)) drum(perc, at, 'kick', L * 0.9);
        if ([3, 6, 9, 11, 14].includes(s)) drum(perc, at, 'conga', L * 0.75, s % 2 ? 1.25 : 1, R);
        drum(perc, at, 'shaker', L * (s % 2 ? 0.18 : 0.3), 1, R);
      } else if (p === 'minimal') { if (s % 4 === 0) drum(perc, at, 'hat', L * 0.4, 1, R); }
    }
    if (b % 4 === 3 && rc.build && rc.perc !== 'none') for (let s = 12; s < 16; s++) drum(perc, t0 + s * step, 'snare', L * 0.3 * (s - 11), 1, R);
    await yieldLoop();
  }
  if (rc.texture > 0) { let lp = 0; for (let i = 0; i < tex.length; i++) { lp = lp * 0.97 + (R() * 2 - 1) * 0.03; tex[i] = lp * rc.texture * 6; } }

  // per-layer processing
  const padLf = filterBuf(padL, 'lp', rc.pad.cutoff * (0.7 + 0.3 * I), 0.9), padRf = filterBuf(padR, 'lp', rc.pad.cutoff * (0.7 + 0.3 * I), 0.9);
  const bassF = filterBuf(bass, 'lp', 400, 0.7);
  const arpF = delay(filterBuf(arp, 'lp', 5000, 0.7), beat * 0.75, 0.38, 0.35);
  const pnoF = reverb(pno, 0.7, 0.45, 0.5);
  const percF = rc.perc === 'cinematic' ? reverb(perc, 0.9, 0.5, 0.4) : compress(perc, 0.5, 3, 0.005, 0.1);
  const texF = filterBuf(tex, 'bp', 900, 0.4);

  const out = stereo(total);
  for (let i = 0; i < total * SR && i < out.l.length; i++) {
    const t = i / SR;
    // build-up: layers swell over the first ~half; intensity-aware
    const swell = rc.build ? 0.5 + 0.5 * Math.min(1, t / (total * 0.55)) : 1;
    const ramp = (x: number | undefined) => (x === undefined ? 1 : Math.max(0, Math.min(1, (t - x * total) / Math.max(0.5, total * 0.1))));       // a layer fades in after its entry point
    const u = t / total, arc = rc.arc === 'rise' ? 0.55 + 0.45 * u : rc.arc === 'arch' ? 0.6 + 0.4 * Math.sin(Math.PI * Math.min(1, u * 1.05)) ** 0.7 : 1;
    const tail = rc.outroSec ? Math.max(0, Math.min(1, (total - 0.5 - t) / rc.outroSec)) : 1, head = arranged ? Math.min(1, t / 0.4) : 1;
    const pad = (padLf[i] + padRf[i]) * 0.5;
    const mid = (pad * swell + bassF[i] * (0.7 + 0.3 * swell) * ramp(rc.layerIn?.bass) + arpF[i] * (rc.build ? Math.min(1, t / 6) : 1) * Math.min(1, I) * ramp(rc.layerIn?.arp) + pnoF[i] * ramp(rc.layerIn?.piano) + percF[i] * (rc.build ? 0.5 + 0.5 * swell : 1) * ramp(rc.layerIn?.perc) + texF[i]) * arc * tail * head;
    out.l[i] = mid + (padLf[i] - pad) * 0.8 * arc * tail * head; out.r[i] = mid + (padRf[i] - pad) * 0.8 * arc * tail * head;
  }
  out.l = reverb(out.l, rc.reverb * 0.6, 0.12 + rc.reverb * 0.14, 0.45); out.r = reverb(out.r, rc.reverb * 0.6, 0.12 + rc.reverb * 0.14, 0.45, 1);
  const tilt: [import('./dsp.ts').FilterType, number, number, number][] = [['highshelf', 6000, 0.7, rc.bright], ['lowshelf', 120, 0.7, 1.5], ['hp', 28, 0.7, 0]];
  out.l = compress(eq(out.l, tilt), 0.6, 2.2, 0.02, 0.2); out.r = compress(eq(out.r, tilt), 0.6, 2.2, 0.02, 0.2);
  const final = { l: out.l.subarray(0, secToN(o.seconds)), r: out.r.subarray(0, secToN(o.seconds)) };
  return normalise(final, 0.7);
}

